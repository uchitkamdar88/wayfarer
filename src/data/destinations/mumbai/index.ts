export function getSeasonForDate(dateString: string): SeasonalIntelligence {
  const d = new Date(dateString);
  const m = isNaN(d.getTime()) ? new Date().getMonth() + 1 : d.getMonth() + 1;
  if (m >= 11 || m <= 2) return MUMBAI_SEASONAL_INTELLIGENCE.winter;
  if (m >= 3 && m <= 5) return MUMBAI_SEASONAL_INTELLIGENCE.summer;
  return MUMBAI_SEASONAL_INTELLIGENCE.monsoon;
}

